/**
 * 개인정보 보관기간 — **단일 진상**.
 *
 * ★★ 왜 한 곳에 모으는가
 *
 *   보관기간이 개인정보처리방침(문서)과 코드에 따로 적혀 있으면 반드시 어긋난다.
 *   그리고 어긋나는 방향이 나쁘다 — 방침은 "3개월 후 파기한다" 고 약속하는데 코드가
 *   지우지 않으면, **약속을 지키지 않는 상태**가 되고 그 증거(오래된 행)가 DB 에 남는다.
 *
 *   실제로 그 상태였다. 자동 파기가 **전혀 없었고**(스케줄러 참조 0건, 수동 CLI 뿐)
 *   `audit_logs` 576행이 서비스 개시일부터 그대로 쌓여 있었다.
 *
 * ★★ 왜 "전부 2년" 으로 통일하지 않는가
 *
 *   항목마다 법이 정한 기간이 다르다. 하나로 묶으면 어떤 것에는 **너무 길고**(수집
 *   최소화 위반) 어떤 것에는 **법정 최소보다 짧다**(보존의무 위반). 둘 다 위법이다.
 *
 *     · 접속기록(IP·UA·시각)   3개월  — 통신비밀보호법 시행령이 정한 기간.
 *                                       더 길게 두면 개인정보보호법 §21(목적 달성 시
 *                                       지체 없이 파기)과 충돌한다.
 *     · 대금결제·재화공급      5년    — 전자상거래법 시행령. **줄일 수 없다.**
 *     · 계약·청약철회          5년    — 같은 법령.
 *     · 소비자 불만·분쟁처리   3년    — 같은 법령.
 *     · 표시·광고              6개월  — 같은 법령.
 *
 *   법정 의무가 없는 항목(자산 스냅샷 등)은 사업 판단으로 정할 수 있다. 거기에만
 *   운영자 결정을 반영한다.
 *
 * ★ 위 기간은 **변호사 확인이 필요하다.** 법령 원문을 이 환경에서 열지 못해 기억에
 *   의존해 적었다. 확인 전에는 기존 처리방침에 적힌 값을 바꾸지 않는다 —
 *   방침을 임의로 줄이는 것이 가장 위험하다.
 */

/** 하루(ms). 달 길이를 평균으로 잡지 않는다 — 파기 기준은 넉넉한 쪽이 안전하다. */
const DAY = 24 * 60 * 60 * 1000;

export interface RetentionRule {
  /** 대상 표. */
  table: string;
  /** 시각 컬럼. 이 값이 기준보다 오래되면 지운다. */
  column: string;
  /** 보관 일수. */
  days: number;
  /**
   * 시각 컬럼의 저장 형태.
   *
   * ★★ 표마다 다르다. `audit_logs.at` 은 timestamptz 인데 `admin_actions.at` 은
   *   **에폭 밀리초(bigint)** 다. 한 가지로 가정하면 한쪽이 조용히 실패한다 —
   *   실제로 운영에서 `invalid input syntax for type bigint` 로 파기가 멈췄다.
   *
   * ★ 새 표를 추가할 때 이 값을 반드시 확인할 것. information_schema 로 확인한다:
   *     SELECT data_type FROM information_schema.columns
   *      WHERE table_name='...' AND column_name='...';
   */
  columnKind: 'timestamptz' | 'epoch_ms';
  /** 사람이 읽는 근거. 로그와 감사에 그대로 쓴다. */
  reason: string;
  /**
   * 법정 의무인가.
   *
   * ★ true 면 **운영자가 줄일 수 없다.** 줄이면 보존의무 위반이다.
   */
  statutory: boolean;
}

/**
 * 접속기록·감사기록 파기 규칙.
 *
 * ★ 거래·결제·동의 기록은 여기에 **넣지 않는다.** 5년 보존의무가 있고, 탈퇴자 몫은
 *   `retained_*` 표로 분리 보관한다(tools/purge-retained.mjs 가 담당). 여기서 지우면
 *   보존의무를 깨뜨린다.
 */
/*
   ★★★ 2026-09-09 법령 원문 대조로 **잘못된 기간을 바로잡았다.**

     이전에는 세 표 모두 90일이었고, audit_logs 의 근거로 「통신비밀보호법 시행령」을
     적어 두었다. 둘 다 틀렸다.

   ① 근거 법을 잘못 적었다
        통신비밀보호법의 통신사실확인자료 보관의무는 **전기통신사업자**의 의무다.
        우리는 전기통신사업자가 아니라 일반 개인정보처리자다. 적용 법령이 아니다.

   ② 기간이 법정 최소치보다 짧았다 — 「개인정보의 안전성 확보조치 기준」
      (개인정보보호위원회 고시 제2026-9호, 2026-07-01 시행) 제8조제1항 원문:

        "개인정보처리자는 개인정보처리시스템에 접속한 자(다만, 정보주체는
         제외한다)의 접속기록을 **1년 이상** 보관ㆍ관리하여야 한다. 다만, 다음 각 호의
         어느 하나에 해당하는 경우에는 **2년 이상** 보관ㆍ관리하여야 한다.
           1. 5만명 이상의 정보주체에 관한 개인정보를 처리하는 개인정보처리시스템
           2. 고유식별정보 또는 민감정보를 처리하는 개인정보처리시스템
           3. ... 기간통신사업자"

      같은 고시 제2조제3호가 "접속기록"을 이렇게 정의한다:
        "개인정보처리시스템에 접속하는 자가 ... 수행한 업무내역에 대하여 식별자,
         접속일시, 접속지 정보, 처리한 정보주체 정보, 수행업무 등을 전자적으로 기록한 것"

      → admin_actions·audit_logs 가 정확히 이것이다. 90일은 **위반이다.**

   ★ 우리는 1년 구간이다: 정보주체 34명(5만 미만) · KYC 를 하지 않으므로 고유식별정보
     없음 · 민감정보 없음 · 기간통신사업자 아님.

   ★★ 2년으로 올려야 하는 조건이 생기면 **여기부터 고쳐야 한다**:
        · 가입자가 5만명을 넘을 때
        · 신분증·주민번호 등 고유식별정보를 받기 시작할 때(KYC 도입)
        · 건강·정치성향 등 민감정보를 처리할 때
      ACCESS_LOG_DAYS 한 곳만 고치면 두 표에 함께 반영된다.

   ★ 다행히 아직 아무것도 지워지지 않았다. 파기 스케줄러는 2026-09-08 에 켰고 그때
     기준 90일 컷오프는 2026-06-11 인데, 가장 오래된 기록이 2026-08-22 였다.
     실측: audit_logs 640행 · admin_actions 4743행 모두 남아 있다.
*/
const ACCESS_LOG_DAYS = 365;

