-- 0022 되돌리기
-- ------------------------------------------------------------
-- ★★ 경고: 이 되돌리기는 **법정 보관 중인 기록을 지운다.**
--
--   `retained_*` 테이블에는 이미 삭제된 회원의 약관 동의·주문 기록이 들어
--   있고, 원본은 그때 지워졌으므로 여기서 DROP 하면 **복구할 수 없다.**
--   우리가 방침에서 5년 보관하겠다고 한 자료가 사라진다.
--
--   개발 환경에서 스키마를 되돌리는 경우가 아니라면 실행하지 말 것.
--   운영에서 되돌려야 한다면 먼저 내용을 내보내 보관한 뒤 실행할 것.
--
--   `user_deletion_records` 는 삭제 처리가 적법했음을 보이는 근거이므로
--   지우면 "왜 지웠는지" 에 답할 수 없게 된다.
-- ============================================================

DROP TABLE IF EXISTS user_deletion_records;
DROP TABLE IF EXISTS retained_orders;
DROP TABLE IF EXISTS retained_legal_consents;
