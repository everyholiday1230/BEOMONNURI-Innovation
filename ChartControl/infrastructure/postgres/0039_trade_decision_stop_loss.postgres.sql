-- 0039 · 학습 데이터에 브래킷 손절가(stop_loss_price)를 분리해 담는다.
--
-- 왜 별도 칼럼인가
-- ---------------
-- 기존 stop_price 는 **발동(조건부) 진입가**다 — "이 가격에 닿으면 진입한다".
-- 브래킷 손절가는 뜻이 정반대다 — "이 가격에 닿으면 포지션을 닫는다".
-- 같은 칼럼에 넣으면 학습 데이터에서 두 사건을 구분할 수 없고, 학습 문장 생성기가
-- 진입 조건을 "손절을 걸었다" 로 읽는다. 실제 매매와 반대되는 문장이 데이터에
-- 들어가는 것이 이 프로젝트에서 가장 피해야 하는 오염이다.
--
-- take_profit_price 는 이미 있다(0025). 손절 쪽만 없어서 브래킷 주문이 절반만
-- 기록되고 있었다 — "no stop attached" 로 잘못 기록된다.
ALTER TABLE trade_decisions
  ADD COLUMN IF NOT EXISTS stop_loss_price NUMERIC;
