-- ============================================================
-- 0050 — 모의(페이퍼) 잔고: 사용자·자산당 한 행만
-- ------------------------------------------------------------
-- 왜 필요한가
--
--   `account_balances` 는 시뮬레이터 잔고를 담는다. 그런데 제약이
--   PRIMARY KEY (id) 뿐이어서 **같은 사용자·같은 자산의 행이 여러 개** 생길 수
--   있었다. 페이퍼 시작 잔고를 지급하는 경로를 새로 만들면서 이것이 문제가 된다:
--
--     · 지급이 두 번 실행되면 잔고가 두 배가 된다(요청 재시도·동시 클릭)
--     · 조회는 행을 합치지 않으므로 화면이 한쪽만 보여준다
--     · 체결마다 잔고를 갱신할 때 어느 행을 고쳐야 할지 알 수 없다
--
--   대회(모의 랭킹)를 하려면 잔고가 정확해야 한다. 두 배로 시작한 참가자가
--   생기면 순위 자체가 무의미해진다.
--
-- 왜 지금 안전한가
--
--   현재 프로덕션 `account_balances` 는 **0행**이다(2026-09-14 확인). 그래서
--   중복 정리 없이 제약만 추가하면 된다. 행이 있는 환경을 위해 정리 구문을
--   먼저 둔다 — 없으면 아무 일도 하지 않는다.
--
-- ★ 되돌리기(down)는 제약만 지운다. 데이터는 건드리지 않는다.
-- ============================================================

-- 혹시 중복이 있으면 가장 최근 것만 남긴다.
-- ★ `at` 이 같으면 id 로 결정한다 — 순서가 없으면 실행마다 다른 행이 남아
--   재현이 불가능해진다.
DELETE FROM account_balances a
USING account_balances b
WHERE a.user_id = b.user_id
  AND a.asset = b.asset
  AND (a.at < b.at OR (a.at = b.at AND a.id < b.id));

CREATE UNIQUE INDEX IF NOT EXISTS account_balances_user_asset_uniq
  ON account_balances (user_id, asset);
