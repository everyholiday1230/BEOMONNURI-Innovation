-- ============================================================
-- 0046 — 거래기록의 AI 학습 이용 동의
-- ------------------------------------------------------------
-- 왜 필요한가
--
--   `trade_learning_dataset`(0025)이 고객의 주문·지표·시장상황·결과를 모으고 있고,
--   그 표의 목적이 스키마 주석에 "나중에 이 기록으로 모델을 학습시킨다" 로 적혀 있다.
--   개인정보처리방침 v1.2 §1.5 에 그 목적을 밝혔다.
--
--   ★★ 그런데 목적을 **밝히는 것**과 **동의를 받는 것**은 다르다.
--
--     개인정보보호법 §28-2 는 가명정보 처리를 통계작성·과학적연구·공익적기록보존
--     목적으로 제한한다. 상용 모델 학습이 '과학적 연구' 에 해당하는지는 법률 검토가
--     필요하고(LEGAL-REVIEW-REQUEST §B-3), 해당하지 않으면 별도 동의가 있어야 한다.
--
--   ★ 어느 해석에서도 안전한 쪽을 택했다 — 동의를 미리 받아 기록해 둔다. 필요 없다는
--     답이 오면 칸을 지우면 되고, 필요하다는 답이 오면 이미 받아 둔 상태가 된다.
--     반대 순서로 가면 **이미 모은 데이터를 쓸 수 없다.**
--
-- ★★ 기본값이 FALSE 다 — 그리고 이 기본값의 의미가 마케팅과 다르다.
--
--   마케팅은 "동의 없으면 안 보낸다" 로 끝난다. 학습은 **이미 수집이 진행 중**이라
--   기존 가입자 전원이 FALSE 가 되고, 그 말은 "현재 동의를 받은 사람이 없다" 는 뜻이다.
--   TRUE 로 채우면 받지 않은 동의를 받았다고 기록하는 것이 된다 — 하지 않는다.
--
--   즉 이 마이그레이션 직후 학습 대상은 **0명**이다. 그것이 사실이다.
--
-- ★ 거절(FALSE + at 있음)을 기본(FALSE + at NULL)과 구별한다. 거절한 고객에게 다시
--   묻는 것과, 아직 묻지 않은 고객에게 처음 묻는 것은 다른 일이다.
-- ============================================================

ALTER TABLE users
  ADD COLUMN IF NOT EXISTS ai_training_opt_in BOOLEAN NOT NULL DEFAULT FALSE;

ALTER TABLE users
  ADD COLUMN IF NOT EXISTS ai_training_opt_in_at TIMESTAMPTZ;

-- 학습 데이터셋을 만들 때 "동의한 사용자" 만 뽑는다. 그 조회가 이 인덱스를 쓴다.
CREATE INDEX IF NOT EXISTS idx_users_ai_training_opt_in
  ON users (ai_training_opt_in_at DESC)
  WHERE ai_training_opt_in = TRUE;
