-- 0017: 포인트 원장에 단조 증가 순번을 넣는다.
--
-- 왜 필요한가 (테스트로 발견한 실제 결함)
-- --------------------------------------
-- 원장 정합성 검사는 "각 항목의 balance_after 가 그 앞 항목들의 합과 같은가"
-- 를 본다. 그러려면 **항목 순서가 하나로 정해져야** 한다.
--
-- 지금은 created_at 으로 정렬하고, 같으면 id(uuid)로 가른다. uuid 는 무작위라
-- 같은 시각에 들어온 항목들의 순서가 삽입 순서와 달라진다. 그러면 정합성
-- 검사가 **정상인 원장을 위반이라고 보고**한다.
--
-- 그 결과가 나쁘다: 운영자가 "원장이 맞지 않습니다" 를 보고 제도를 멈춘다.
-- 아무 문제가 없는데. 거짓 경보를 내는 감시는 없는 것보다 나쁘다 — 몇 번
-- 겪으면 진짜 경보도 무시하게 된다.
--
-- 실제로 동시 적립 8건 테스트에서 5건이 거짓 위반으로 보고됐다.
--
-- bigserial 은 삽입 순서를 보장한다. 트랜잭션이 롤백되면 번호에 구멍이 생기지만
-- 순서는 어긋나지 않는다 — 정합성 검사에는 순서만 필요하다.

ALTER TABLE point_ledger ADD COLUMN IF NOT EXISTS seq bigserial;

-- 사용자별 원장 조회와 정합성 검사가 모두 이 순서를 쓴다.
CREATE INDEX IF NOT EXISTS idx_points_user_seq ON point_ledger (user_id, seq);
